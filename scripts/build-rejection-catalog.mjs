#!/usr/bin/env node
/**
 * Regenerates rejeicoesCatalog.ts from the official "Anexo I - Leiaute e Regras
 * de Negocio" workbook published at gov.br/nfse (sheet "RN DPS_NFS-e").
 *
 *   node scripts/build-rejection-catalog.mjs <anexo_i.xlsx> <versao> <url>
 *
 * Only Node built-ins: the .xlsx (a zip of XML files) is read directly.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';

const sources = process.argv.slice(2).map((arg) => {
  const [file, documento, url] = arg.split("|");
  if (!file || !documento || !url) throw new Error(`expected "<xlsx>|<documento>|<url>", got: ${arg}`);
  return { file, documento, url };
});
if (!sources.length) {
  console.error('usage: build-rejection-catalog.mjs "<xlsx>|<documento>|<url>" [...]');
  process.exit(1);
}

function unzip(buffer) {
  const eocd = buffer.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  const count = buffer.readUInt16LE(eocd + 10);
  let offset = buffer.readUInt32LE(eocd + 16);
  const entries = new Map();
  for (let i = 0; i < count; i++) {
    const method = buffer.readUInt16LE(offset + 10);
    const size = buffer.readUInt32LE(offset + 20);
    const nameLength = buffer.readUInt16LE(offset + 28);
    const extraLength = buffer.readUInt16LE(offset + 30);
    const commentLength = buffer.readUInt16LE(offset + 32);
    const local = buffer.readUInt32LE(offset + 42);
    const name = buffer.toString('utf8', offset + 46, offset + 46 + nameLength);
    const dataStart = local + 30 + buffer.readUInt16LE(local + 26) + buffer.readUInt16LE(local + 28);
    const data = buffer.subarray(dataStart, dataStart + size);
    entries.set(name, method === 8 ? inflateRawSync(data) : data);
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return entries;
}

const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&#10;/g, '\n').replace(/&amp;/g, '&');
const clean = (s) => String(s ?? '').replace(/\r\n?/g, '\n').replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();

function sheets(file) {
  const zip = unzip(readFileSync(file));
  const text = (name) => zip.get(name).toString('utf8');
  const shared = [...text('xl/sharedStrings.xml').matchAll(/<si>([\s\S]*?)<\/si>/g)]
    .map((m) => decode([...m[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((t) => t[1]).join('')));
  const rels = text('xl/_rels/workbook.xml.rels');
  return [...text('xl/workbook.xml').matchAll(/<sheet name="([^"]+)"[^>]*r:id="([^"]+)"/g)].map(([, name, id]) => {
    const target = rels.match(new RegExp(`Id="${id}"[^>]*Target="([^"]+)"`))?.[1];
    const rows = [];
    for (const row of text(`xl/${target}`).matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
      const cells = {};
      for (const c of row[1].matchAll(/<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
        const value = c[3]?.match(/<v>([\s\S]*?)<\/v>/)?.[1];
        const inline = c[3]?.match(/<t[^>]*>([\s\S]*?)<\/t>/)?.[1];
        cells[c[1]] = clean(/t="s"/.test(c[2]) ? shared[Number(value)] : decode(inline ?? value ?? ''));
      }
      rows.push(cells);
    }
    return { name, rows };
  });
}

/** Finds a column whose header (first rows) matches the pattern. */
function column(rows, pattern) {
  for (const row of rows.slice(0, 6)) {
    for (const [col, value] of Object.entries(row)) if (pattern.test(value)) return col;
  }
  return undefined;
}

const catalog = new Map();
sources.forEach((source, fonte) => {
  for (const { name, rows } of sheets(source.file)) {
    const codeCol = column(rows, /^C[ÓO]D\.? ?ERRO$/i);
    if (!codeCol) continue;
    const cols = {
      mensagem: column(rows, /^MSG\.? ?ERRO$/i),
      regra: column(rows, /^REGRAS? DE NEG[ÓO]CIO$/i),
      caminho: column(rows, /^CAMINHO NO XML$/i),
      campo: column(rows, /^CAMPO$/i),
      nivel: column(rows, /^N[ÍI]VEL/i),
    };
    let caminho = '';
    let campo = '';
    for (const row of rows) {
      if (cols.caminho && row[cols.caminho] && row[cols.caminho] !== '-') caminho = row[cols.caminho];
      if (cols.campo && row[cols.campo] && row[cols.campo] !== '-') campo = row[cols.campo];
      const codigo = row[codeCol];
      if (!/^E\d{4}$/.test(codigo ?? '')) continue;
      if (catalog.has(codigo)) continue; // first source wins
      const entry = { codigo, mensagem: row[cols.mensagem] ?? '', regra: (cols.regra && row[cols.regra]) || '', fonte };
      if (caminho || campo) entry.campo = `${caminho}${campo}`;
      const nivel = Number(cols.nivel && row[cols.nivel]);
      if (nivel) entry.nivel = nivel;
      entry.planilha = name.trim();
      catalog.set(codigo, entry);
    }
  }
});

const entries = [...catalog.values()].sort((a, b) => a.codigo.localeCompare(b.codigo));
const header = `// Generated by scripts/build-rejection-catalog.mjs. Do not edit by hand.

import type { RejeicaoOficial } from './rejeicoes.js';

/** Official spreadsheets this catalog was generated from (gov.br/nfse, documentacao atual). */
export const REJEICOES_FONTES = ${JSON.stringify(sources.map(({ documento, url }) => ({ documento, url })), null, 2)} as const;

export const REJEICOES_OFICIAIS: readonly RejeicaoOficial[] = `;
writeFileSync('rejeicoesCatalog.ts', `${header}${JSON.stringify(entries, null, 2)};\n`);
console.log(`rejeicoesCatalog.ts: ${entries.length} codes`);
